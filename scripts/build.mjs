import {build} from 'esbuild';
import {mkdir,readFile,writeFile,copyFile} from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {bundleRuntime,nodeVersion} from './runtime.mjs';
import {platformConfig,mcpTransport,buildProfile} from './platform.mjs';
const target=platformConfig();
const preset=process.argv.includes('--cuda')?`${target.windows?'windows':'linux'}-cuda`:process.env.BETTER_SEARCH_BUILD_PRESET||target.preset;
const profile=buildProfile(preset);
const native=path.resolve(profile.binary);
const info=JSON.parse(execFileSync(native,['--build-info'],{encoding:'utf8'}));
const pkg=JSON.parse(await readFile('package.json','utf8'));
if(info.version!==pkg.version||info.profile!==preset)throw Error('Native binary version/profile does not match the requested build');
await mkdir('dist/ui',{recursive:true});await mkdir('dist/native',{recursive:true});await mkdir('dist/runtime',{recursive:true});
await build({entryPoints:['src/mcp.ts','src/launcher.ts'],bundle:true,platform:'node',target:'node22',format:'esm',outdir:'dist',banner:{js:"import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);"}});
const ui=await build({entryPoints:['src/ui.ts'],bundle:true,platform:'browser',target:'es2022',format:'iife',write:false,minify:true});
await writeFile('dist/ui/index.html',(await readFile('src/index.html','utf8')).replace('/* BETTER_SEARCH_UI_SCRIPT */',()=>ui.outputFiles[0].text.replace(/<\/script/gi,'<\\/script')));
await copyFile(native,path.join('dist/native',target.nativeName));
if(!target.windows)await copyFile(path.join(path.dirname(profile.binary),'better-search-dialog'),'dist/native/better-search-dialog');
await bundleRuntime(path.resolve('dist/runtime'),target);
await writeFile('dist/mcp-config.json',JSON.stringify({mcpServers:{'better-search':mcpTransport()}},null,2)+'\n');
const commit=execFileSync('git',['-C','third_party/llama.cpp','rev-parse','HEAD'],{encoding:'utf8'}).trim();
await writeFile('dist/build-info.json',JSON.stringify({...info,target:target.target,accelerator:profile.accelerator,llamaCommit:commit,node:nodeVersion,backend:'C++20',inference:'llama.cpp linked in process',builtAt:new Date().toISOString()},null,2)+'\n');
console.log(`Built BetterSearch ${pkg.version}: ${preset}, bundled Node ${nodeVersion}, one conversation panel.`);
